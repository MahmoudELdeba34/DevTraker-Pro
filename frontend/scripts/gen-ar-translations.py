def translate(en: str) -> str:
    if en in KEEP:
        return en
    if en in T:
        return T[en]
    # fallback: keep English but flag for review
    return en

def main():
    content = EN_PATH.read_text(encoding="utf-8")
    pattern = re.compile(r"^(\s+'([^']+)':\s+)'((?:\\'|[^'])*)'(,?)$", re.MULTILINE)

    missing = []

    def repl(m):
        prefix, key, val, comma = m.group(1), m.group(2), m.group(3), m.group(4)
        raw = val.replace("\\'", "'")
        ar = translate(raw)
        if ar == raw and raw not in KEEP and not raw.startswith("{{"):
            missing.append((key, raw))
        escaped = ar.replace("'", "\\'")
        return f"{prefix}'{escaped}'{comma}"

    out = pattern.sub(repl, content)
    out = out.replace("export const EN:", "export const AR:")
    AR_PATH.write_text(out, encoding="utf-8")
    print(f"Wrote {AR_PATH}")
    print(f"Untranslated: {len(missing)}")
    for k, v in missing[:30]:
        print(f"  {k}: {v}")

if __name__ == "__main__":
    main()
